def run_app(db: DatabaseSettings, statement: str, **params: object) -> list:
    """One statement on the scratch database as the app role (never ``run_admin``: that is the maintenance database).

    Returns the first column of the rows, if any."""

    assert db.name.startswith("specflow_pytest_"), "not a scratch database"

    async def execute() -> list:
        engine = create_async_engine(db.url(), connect_args=db.connect_args())
        try:
            async with engine.begin() as connection:
                result = await connection.execute(text(statement), params)
                return [row[0] for row in result] if result.returns_rows else []
        finally:
            await engine.dispose()

    return asyncio.run(execute())


def insert_user(db: DatabaseSettings, email: str) -> uuid.UUID:
    user = uuid.uuid4()
    run_app(
        db,
        "INSERT INTO users (id, actor_id, display_name, email) VALUES (:id, :actor, 'n', :email)",
        id=user,
        actor=f"actor-{user}",
        email=email,
    )
    return user


def insert_project(db: DatabaseSettings, owner: uuid.UUID, role: str | None = "owner") -> uuid.UUID:
    project = uuid.uuid4()
    run_app(db, "INSERT INTO projects (id, name, created_by) VALUES (:id, 'P', :owner)", id=project, owner=owner)
    if role is not None:
        add_member(db, project, owner, role)
    return project


def add_member(db: DatabaseSettings, project: uuid.UUID, user: uuid.UUID, role: str) -> None:
    run_app(
        db,
        "INSERT INTO project_members (project_id, user_id, role) VALUES (:project, :user, :role)",
        project=project,
        user=user,
        role=role,
    )


def add_invite(db: DatabaseSettings, project: uuid.UUID, invited_by: uuid.UUID, email: str) -> None:
    run_app(
        db,
        "INSERT INTO project_invites (id, project_id, email_norm, invited_by) VALUES (:id, :project, :email, :by)",
        id=uuid.uuid4(),
        project=project,
        email=email,
        by=invited_by,
    )


def test_l13_second_owner_and_unknown_role_are_refused_after_upgrade(migrated_database: DatabaseSettings) -> None:
    """FR-PRJ-ROLE-02: one owner per project (unique index); a collaborator is not limited."""

    ana, bob, cy = (insert_user(migrated_database, f"{n}@example.com") for n in ("ana", "bob", "cy"))
    project = insert_project(migrated_database, ana, role="owner")

    with pytest.raises(Exception, match="ux_project_members_one_owner"):
        add_member(migrated_database, project, bob, "owner")
    add_member(migrated_database, project, bob, "collaborator")
    add_member(migrated_database, project, cy, "collaborator")
    with pytest.raises(Exception, match="ck_project_members_role"):
        add_member(migrated_database, project, ana, "editor")
    with pytest.raises(Exception, match="role"):  # DM3: no default, every insert states its role
        run_app(
            migrated_database,
            "INSERT INTO project_members (project_id, user_id) VALUES (:project, :user)",
            project=project,
            user=ana,
        )


def test_l15_project_invites_constraints(migrated_database: DatabaseSettings) -> None:
    ana = insert_user(migrated_database, "ana@example.com")
    project = insert_project(migrated_database, ana, role="owner")

    def invite(email: str) -> None:
        add_invite(migrated_database, project, ana, email)

    invite("new@example.com")
    with pytest.raises(Exception, match="uq_project_invites_project_id_email_norm"):
        invite("new@example.com")
    for bad in ("New@example.com", " new2@example.com"):
        with pytest.raises(Exception, match="ck_project_invites_email_norm"):
            invite(bad)


def test_l16_project_invites_has_rls_and_the_agent_has_no_grant(migrated_database: DatabaseSettings) -> None:
    """NFR-PRJ-05: RLS on, the policy exists, and the agent role has no privilege on the table."""

    assert query_column(
        migrated_database,
        "SELECT relrowsecurity::text FROM pg_class WHERE relname = 'project_invites'",
    ) == ["true"]
    assert query_column(
        migrated_database,
        "SELECT policyname FROM pg_policies WHERE tablename = 'project_invites'",
    ) == ["agent_project_scope"]
    assert query_column(
        migrated_database,
        "SELECT count(*) FROM pg_class WHERE relkind = 'r' AND relrowsecurity "
        "AND relnamespace = 'public'::regnamespace",
    ) == [6]  # the five scoped tables of before, plus project_invites
    assert run_app(
        migrated_database,
        "SELECT has_table_privilege(:role, 'project_invites', 'SELECT,INSERT,UPDATE,DELETE')::text",
        role=SESSION_AGENT_ROLE,
    ) == ["false"]
