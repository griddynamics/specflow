"""Tier 2: the migrations and the async engine against a real Postgres.

Skipped unless ``SPECFLOW_TEST_POSTGRES=1``, so ``make check`` never needs a
database:

    make up        # repository root; the postgres service (or the whole stack)
    SPECFLOW_TEST_POSTGRES=1 uv run --env-file ../.env.local \\
        pytest tests/test_db_migrations_live.py

Every migration test migrates its own scratch database and binds RLS to the
session test role ``specflow_agent_test_<hex8>`` (fixtures in specflow_db_live_support).
The Alembic tests are sync ``def``s: migrations/env.py calls ``asyncio.run``,
which cannot run inside the event loop an ``async def`` test would hold.
"""

from __future__ import annotations

import re
import uuid

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from db import migrate
from db.base import Base
from db.session import build_engine, build_session_factory
from settings import DatabaseSettings, load_settings
from specflow_db_live_support import (
    SESSION_AGENT_ROLE,
    AgentRole,
    alembic_config,
    query_column,
    quote,
    run_admin,
)
from specflow_live import requires_live

pytestmark = requires_live("POSTGRES")

APP_TABLES = [
    "connection_items",
    "connections",
    "documents",
    "project_members",
    "projects",
    "users",
]
HEAD = "0001_initial"
TABLES_SQL = (
    "SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename <> 'alembic_version' ORDER BY tablename"
)


def ddl(element: CreateTable) -> str:
    return str(element.compile(dialect=postgresql.dialect()))


def stamped_versions(scratch: DatabaseSettings) -> list[str]:
    return query_column(scratch, "SELECT version_num FROM alembic_version")


def test_l1_upgrade_head_on_an_empty_database_creates_the_app_tables(
    scratch_database: DatabaseSettings, agent_role: AgentRole
) -> None:
    command.upgrade(alembic_config(scratch_database), "head")

    assert stamped_versions(scratch_database) == [HEAD]
    assert query_column(scratch_database, TABLES_SQL) == APP_TABLES


def test_l2_upgrade_head_twice_is_a_no_op(scratch_database: DatabaseSettings, agent_role: AgentRole) -> None:
    cfg = alembic_config(scratch_database)

    command.upgrade(cfg, "head")
    command.upgrade(cfg, "head")

    assert stamped_versions(scratch_database) == [HEAD]


def test_l3_alembic_check_finds_no_difference_to_the_models(
    migrated_database: DatabaseSettings,
) -> None:
    try:
        command.check(alembic_config(migrated_database))
    except AutogenerateDiffsDetected as error:
        pytest.fail(f"models and migrations differ: {error}")


def test_l4_downgrade_to_base_and_upgrade_again(
    migrated_database: DatabaseSettings,
) -> None:
    cfg = alembic_config(migrated_database)

    command.downgrade(cfg, "base")
    assert stamped_versions(migrated_database) == []
    assert query_column(migrated_database, TABLES_SQL) == []
    # dropping the tables took their policies and the agent's column grant with them
    assert query_column(migrated_database, "SELECT policyname FROM pg_policies WHERE schemaname = 'public'") == []

    command.upgrade(cfg, "head")
    assert stamped_versions(migrated_database) == [HEAD]
    assert query_column(migrated_database, TABLES_SQL) == APP_TABLES


def test_l5_downgrade_base_empties_the_version_table(
    migrated_database: DatabaseSettings,
) -> None:
    command.downgrade(alembic_config(migrated_database), "base")

    assert stamped_versions(migrated_database) == []


def test_l6_the_upgrade_fails_naming_the_variable_when_the_role_is_missing(
    scratch_database: DatabaseSettings,
) -> None:
    missing = f"specflow_agent_missing_{uuid.uuid4().hex[:6]}"
    cfg = alembic_config(scratch_database, missing)

    with pytest.raises(RuntimeError, match="DATABASE_AGENT_USER") as caught:
        command.upgrade(cfg, "head")

    assert missing in str(caught.value)
    # One transaction for the whole run: nothing stays behind.
    assert query_column(scratch_database, TABLES_SQL) == []


def test_l7_specflow_migrate_runs_head_and_a_second_run_is_a_no_op(
    scratch_database: DatabaseSettings,
    agent_role: AgentRole,
    valid_env: dict[str, str],
) -> None:
    db = scratch_database
    env = {
        **valid_env,
        "DATABASE_HOST": db.host,
        "DATABASE_PORT": str(db.port),
        "DATABASE_NAME": db.name,
        "DATABASE_USER": db.user,
        "DATABASE_PASSWORD": db.password.get_secret_value(),
        "DATABASE_AGENT_USER": agent_role.name,
    }
    settings = load_settings("migrate", env)

    assert migrate.run(settings) == 0
    assert stamped_versions(db) == [HEAD]
    assert migrate.run(settings) == 0
    assert stamped_versions(db) == [HEAD]


async def test_l8_the_async_engine_runs_a_session_query(
    configured_database: DatabaseSettings,
) -> None:
    engine = build_engine(configured_database)
    try:
        async with build_session_factory(engine)() as session:
            result = await session.execute(text("SELECT 1"))
            assert result.scalar_one() == 1
    finally:
        await engine.dispose()


@pytest.mark.parametrize("flag", ["BYPASSRLS", "SUPERUSER"])
def test_l9_the_upgrade_refuses_an_agent_role_that_bypasses_rls(
    scratch_database: DatabaseSettings,
    configured_database: DatabaseSettings,
    flag: str,
) -> None:
    unsafe = f"{SESSION_AGENT_ROLE}_{flag.lower()}"
    run_admin(configured_database, f"CREATE ROLE {quote(unsafe)} NOLOGIN {flag}")
    try:
        with pytest.raises(RuntimeError, match="DATABASE_AGENT_USER") as caught:
            command.upgrade(alembic_config(scratch_database, unsafe), "head")
        assert "BYPASSRLS" in str(caught.value)
        assert query_column(scratch_database, TABLES_SQL) == []
    finally:
        run_admin(configured_database, f"DROP ROLE IF EXISTS {quote(unsafe)}")


def test_l10_constraint_and_index_names_match_the_models_exactly(
    migrated_database: DatabaseSettings,
) -> None:
    """``alembic check`` ignores CHECK names; compare the catalog with the metadata DDL."""

    expected: set[str] = set()
    for table in Base.metadata.sorted_tables:
        expected |= set(re.findall(r"CONSTRAINT (\w+)", ddl(CreateTable(table))))
        expected |= {str(index.name) for index in table.indexes}
    found = set(
        query_column(
            migrated_database,
            "SELECT conname FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace "
            "WHERE n.nspname = 'public' AND conname <> 'alembic_version_pkc' "
            "UNION SELECT indexname FROM pg_indexes WHERE schemaname = 'public' "
            "AND indexname <> 'alembic_version_pkc'",
        )
    )

    # Unique and primary-key constraints also own an index of the same name.
    assert found == expected
    assert not [name for name in found if re.match(r"(ck|uq|fk|pk|ix)_\w*_(ck|uq|fk|pk|ix)_", name)]
    assert "ck_documents_status" in found
