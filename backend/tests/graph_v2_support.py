SHOP_V2_DIR: Final = Path(__file__).resolve().parent / "fixtures" / "graph" / "shop-v2"

# Conform judge verdicts by subject name, then loser name: ``(answer, quote)``; the quote is cited
# from the request fragment that holds it (``relates`` needs one, ``unrelated`` cites nothing).
CONFORM_VERDICTS: Final[dict[str, dict[str, tuple[str, str | None]]]] = {
    "Customer can export order history as CSV": {
        "Reporting service": ("relates", "The file is generated by the Reporting service."),
        "Web app": ("unrelated", None),
    },
}
# Attach-orphan verdicts by subject name: the candidate to attach and a quote of a request fragment.
ORPHAN_VERDICTS: Final[dict[str, tuple[str, str]]] = {
    "Partial refunds": ("Orders service", "Partial refunds is a part of the Refunds feature"),
}
JUDGE_CONFIDENCE: Final = 0.9

# shop-v2/4: the requirements of the cross-document links, by name.
CHARGE_RESULT: Final = "Customer sees the result of every card charge"
CHARGE_RECORD: Final = "System records every card charge with amount, currency, result"
SAVED_CARD: Final = "Customer can pay with a saved card"
SAVED_CARD_RULE: Final = "Saved cards are kept only as Stripe tokens"
REFUND_CURRENCY: Final = "In which currency are refunds paid?"
RETRY_QUESTION: Final = "How many times and how far apart is a failed card charge retried?"


@dataclass(frozen=True)
class XdocLink:
    """A ``cross_document`` link the judge gives: members ``a`` and ``b`` by name, its ``relation``, the
    ``source`` member (the one that waits, for a dependency) and quotes of both members' fragments."""

    a: str
    b: str
    relation: str
    source: str
    quotes: tuple[str, ...]


# INF-XDOC-01 verdicts by hub name: one link with a quote from each side (accepted) and one DEPENDS_ON
# whose source-side quote holds no dependency cue (written downgraded, as RELATES_TO).
XDOC_VERDICTS: Final[dict[str, tuple[XdocLink, ...]]] = {
    "Payment service": (
        XdocLink(
            CHARGE_RESULT,
            CHARGE_RECORD,
            "RELATES_TO",
            CHARGE_RESULT,
            (
                "It shows the customer the result of every card charge that the Payment service returns.",
                "Every card charge is recorded with its amount, currency and result.",
            ),
        ),
        XdocLink(
            SAVED_CARD,
            SAVED_CARD_RULE,
            "DEPENDS_ON",
            SAVED_CARD,
            (
                "Customers can pay with a card they saved in an earlier order.",
                "A saved card is kept only as a token from Stripe",
            ),
        ),
    ),
}
# Answered-elsewhere verdicts by question name: the answer and its quote.
ANSWERED_VERDICTS: Final[dict[str, tuple[str, str]]] = {
    REFUND_CURRENCY: ("answered", "Refunds are always paid in the currency of the original order"),
    RETRY_QUESTION: ("partly", "A failed card charge is retried three times before the order is cancelled."),
}
# The fragment (handle) answering each question, near the question's search vector at ``ANSWER_COSINE``.
ANSWER_PASSAGES: Final[dict[str, str]] = {REFUND_CURRENCY: "ps.refunds", RETRY_QUESTION: "ps.retries"}
ANSWER_COSINE: Final = 0.8
# The INF-XDOC-01 member pairs near each other ``(label, name)``, at ``XDOC_COSINE``: above the rule's
# ``pair_floor``, below the requirement dedup floors.
XDOC_PAIRS: Final = (
    (("FunctionalRequirement", CHARGE_RESULT), ("FunctionalRequirement", CHARGE_RECORD)),
    (("FunctionalRequirement", SAVED_CARD), ("Constraint", SAVED_CARD_RULE)),
)
XDOC_COSINE: Final = 0.65


@dataclass(frozen=True)
class Nearness:
    """The search vector of every node whose search text starts with ``prefix`` lies at ``cosine`` to
    the search vector of ``anchor`` (``"<Label>: <name>. <stmt>"``, as Conform writes it)."""

    anchor: str
    prefix: str
    cosine: float


def search_text(answers: ShopAnswers, label: str, name: str) -> str:
    """The search embedding text Conform computes for a node of the answer file (label, name, stmt)."""

    stmt = answers.attributes.get(name, {}).get("stmt")
    return f"{label}: {name}. {stmt}" if stmt else f"{label}: {name}"


def nearness(answers: ShopAnswers) -> tuple[Nearness, ...]:
    """The orphan feature "Partial refunds" is most similar to the Orders service (INF-CONT-02); each
    ``XDOC_PAIRS`` pair whose names the answers hold lies near (INF-XDOC-01)."""

    pairs = tuple(
        Nearness(search_text(answers, *first), f"{second[0]}: {second[1]}.", XDOC_COSINE)
        for first, second in XDOC_PAIRS
        if first[1] in answers.attributes and second[1] in answers.attributes
    )
    return (Nearness(search_text(answers, "Module", "Orders service"), "Feature: Partial refunds.", 0.8), *pairs)


def relate_answer_passages(gateway: ScriptedGateway, answers: ShopAnswers) -> ScriptedGateway:
    """Put each ``ANSWER_PASSAGES`` fragment the answers declare near its question's search vector."""

    for question, handle in ANSWER_PASSAGES.items():
        if handle in answers.fragments and question in answers.attributes:
            anchor = search_text(answers, "OpenQuestion", question)
            gateway.relate(anchor, ANSWER_COSINE, matching=answers.fragment_text_matcher([handle]))
    return gateway


def shop_v2_corpus(snapshot: int, index_root: Path) -> FileCorpusSource:
    return FileCorpusSource(SHOP_V2_DIR / str(snapshot), Path(index_root))


def shop_v2_answer_data(snapshot: int) -> dict[str, Any]:
    path = SHOP_V2_DIR / "answers" / f"{snapshot}.yaml"
    return yaml.safe_load(path.read_text(encoding="utf-8"))


@cache
def shop_v2_answers(snapshot: int) -> ShopAnswers:
    return ShopAnswers(shop_v2_answer_data(snapshot), source=f"shop-v2/{snapshot}.yaml")


def _cited(gateway: ScriptedGateway, request: ScriptedRequest, quote: str) -> dict[str, str]:
    """``quote`` cited from the first request fragment holding it (whitespace-normalised)."""

    for label, body in untrusted_blocks(request.user):
        if label != "payload" and quote in " ".join(body.split()):
            return {"fragment_id": label, "quote": quote}
    message = f"quote {quote!r} for {judge_subject(request)!r} is in no fragment of the request"
    gateway.unscripted.append(message)
    raise ScriptError(message)


def script_conform_judge(
    gateway: ScriptedGateway,
    ontology: Ontology,
    verdicts: Mapping[str, Mapping[str, tuple[str, str | None]]] = CONFORM_VERDICTS,
) -> ScriptedGateway:
    """Script the ontology's conform judge: per subject, each payload loser answered by name; a subject
    or loser without a verdict stays unscripted (the test fails)."""

    spec = ontology.conform_spec()
    if spec is None:
        return gateway

    def handle(request: ScriptedRequest) -> Any:
        by_loser = verdicts.get(judge_subject(request))
        losers = judge_payload(request)["losers"]
        if by_loser is None or any(loser["name"] not in by_loser for loser in losers):
            return NO_ANSWER
        answers, cited = [], []
        for loser in losers:
            answer, quote = by_loser[loser["name"]]
            evidence = [_cited(gateway, request, quote)] if quote else []
            cited.extend(evidence)
            answers.append({"id": loser["id"], "answer": answer, "evidence": evidence})
        return {"confidence": JUDGE_CONFIDENCE, "evidence": cited, "answers": answers}

    gateway.key_by(spec.judge_prompt, judge_subject).handle(spec.judge_prompt, handle)
    return gateway


def script_answered_judge(
    gateway: ScriptedGateway, ontology: Ontology, verdicts: Mapping[str, tuple[str, str]] = ANSWERED_VERDICTS
) -> ScriptedGateway:
    """Script the ontology's answered-elsewhere judge by question name: each verdict's answer with its
    quote cited from the candidate fragment that holds it; a question without one stays unscripted."""

    spec = ontology.conform_spec()
    flag = spec.answered_elsewhere if spec is not None else None
    if flag is None:
        return gateway

    def question(request: ScriptedRequest) -> str:
        return str(judge_payload(request)["question"]["name"])

    def handle(request: ScriptedRequest) -> Any:
        verdict = verdicts.get(question(request))
        if verdict is None:
            return NO_ANSWER
        answer, quote = verdict
        cited = _cited(gateway, request, quote)
        return {"answer": answer, "fragment": cited["fragment_id"], "quote": quote, "confidence": JUDGE_CONFIDENCE}

    gateway.key_by(flag.prompt, question).handle(flag.prompt, handle)
    return gateway


def _cross_document(gateway: ScriptedGateway, request: ScriptedRequest, links: tuple[XdocLink, ...]) -> dict[str, Any]:
    """A ``cross_document`` verdict with ``links``, members named by their payload ids."""

    ids = {member["name"]: member["id"] for member in judge_payload(request)["members"]}
    missing = [name for link in links for name in (link.a, link.b) if name not in ids]
    if missing:
        message = f"members {missing} for {judge_subject(request)!r} are not in the request"
        gateway.unscripted.append(message)
        raise ScriptError(message)
    answers = [
        {
            "a": ids[link.a],
            "b": ids[link.b],
            "relation": link.relation,
            "source": ids[link.source],
            "confidence": JUDGE_CONFIDENCE,
            "evidence": [_cited(gateway, request, quote) for quote in link.quotes],
        }
        for link in links
    ]
    cited = [item for answer in answers for item in answer["evidence"]]
    return {"confidence": JUDGE_CONFIDENCE, "evidence": cited, "links": answers, "owners": []}


def script_inference_judge(
    gateway: ScriptedGateway,
    ontology: Ontology,
    verdicts: Mapping[str, tuple[str, str]] = ORPHAN_VERDICTS,
    links: Mapping[str, tuple[XdocLink, ...]] = XDOC_VERDICTS,
) -> ScriptedGateway:
    """Script every inference rule's judge prompt by subject name: ``verdicts`` for attach-orphan
    subjects, ``links`` for cross-document hubs, a "no link" verdict for every other subject."""

    def handler(template: str) -> Handler:
        def handle(request: ScriptedRequest) -> Any:
            found = links.get(judge_subject(request)) if template == "cross_document" else None
            if found is not None:
                return _cross_document(gateway, request, found)
            verdict = verdicts.get(judge_subject(request)) if template == "attach_orphan" else None
            if verdict is None:
                return copy.deepcopy(NO_LINK_VERDICTS[template])
            target, quote = verdict
            ids = [item["id"] for item in judge_payload(request)["candidates"] if item["name"] == target]
            if len(ids) != 1:
                message = f"candidate {target!r} for {judge_subject(request)!r} is not in the request"
                gateway.unscripted.append(message)
                raise ScriptError(message)
            evidence = [_cited(gateway, request, quote)]
            return {"confidence": JUDGE_CONFIDENCE, "evidence": evidence, "target": ids[0]}

        return handle

    for rule in ontology.inference.rules:
        gateway.key_by(rule.prompt, judge_subject).handle(rule.prompt, handler(rule.template))
    return gateway


@dataclass
class ShopV2Builds:
    """Builds of shop-v2 snapshots into one project with inference on, sharing the file stores and the
    corpus index under ``root``; every model answer is hand-written (``ShopAnswers`` plus the judge
    scripts above)."""

    project: GraphProject
    factory: Callable[..., ScriptedGateway]
    root: Path
    project_id: str = ""
    ontology: Ontology = field(default_factory=shipped_ontology)
    llm: LLMConfig = field(default_factory=live_llm_config)
    hub_params: ConsolidationParams | None = None
    stores: FileStores = field(init=False)

    def __post_init__(self) -> None:
        self.root = Path(self.root)
        self.project_id = self.project_id or self.project.project_id
        self.stores = open_file_stores(self.root)

    def gateway(self, snapshot: int) -> ScriptedGateway:
        answers = shop_v2_answers(snapshot)
        gateway = answers.install(self.factory(self.llm), self.ontology)
        for near in nearness(answers):
            gateway.relate(near.anchor, near.cosine, matching=lambda text, prefix=near.prefix: text.startswith(prefix))
        relate_answer_passages(gateway, answers)
        script_conform_judge(gateway, self.ontology)
        script_answered_judge(gateway, self.ontology)
        return script_inference_judge(gateway, self.ontology)

    def context(self, snapshot: int, gateway: Any, corpus: Path | None = None) -> BuildContext:
        """``corpus``: a corpus folder in place of the snapshot's (a copy with a document left out)."""

        return BuildContext(
            project_id=self.project_id,
            ontology=self.ontology,
            driver=self.project.store,
            gateway=gateway,
            registry=self.stores.registry,
            corpus=FileCorpusSource(corpus, self.root) if corpus else shop_v2_corpus(snapshot, self.root),
            extraction=self.stores.extraction,
            builds=self.stores.builds,
            options=shop_v2_answers(snapshot).options,
            settings=BuildSettings(inference=True),
        )

    async def build(self, snapshot: int, corpus: Path | None = None) -> tuple[BuildResult, ScriptedGateway]:
        """A build of ``snapshot`` with its answers; ``corpus``: another folder to read the documents from."""

        gateway = self.gateway(snapshot)
        with pytest.MonkeyPatch.context() as patch:
            if self.hub_params is not None:
                params = self.hub_params
                patch.setattr(resolution, "ConsolidationParams", lambda: params)
            return await run_shop_build(self.context(snapshot, gateway, corpus)), gateway


def shop_v2_without(snapshot: int, documents: Collection[str], into: Path) -> Path:
    """A copy of the snapshot's corpus folder under ``into`` without ``documents`` (file names): the
    snapshot with those documents deleted. The other files are byte-identical, so their lineages and
    fragments stay the same."""

    target = Path(into) / f"{snapshot}-without"
    shutil.copytree(SHOP_V2_DIR / str(snapshot), target, ignore=lambda _, names: [n for n in names if n in documents])
    return target


def has_short_cycle(edges: list[ProbeEdge], starts: set[str], limit: int) -> bool:
    """Whether a directed path of 1 to ``limit`` of ``edges`` leads from a node of ``starts`` back to it."""

    outgoing: dict[str, set[str]] = {}
    for e in edges:
        outgoing.setdefault(e.source.id, set()).add(e.target.id)
    for start in starts:
        frontier, seen = {start}, set()
        for _ in range(limit):
            frontier = {t for current in frontier for t in outgoing.get(current, ())} - seen
            if start in frontier:
                return True
            seen |= frontier
    return False
