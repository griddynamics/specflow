async def test_an_owner_chain_drops_every_redundant_link_whatever_the_order() -> None:
    grouped = ONT.relations["GROUPED_BY"]
    pairs = tuple(
        dataclasses.replace(pair, redundant_via_owner=True) if pair.source == FEAT else pair for pair in grouped.pairs
    )
    pairs += (dataclasses.replace(pairs[0], source=MOD, redundant_via_owner=False),)
    chained = dataclasses.replace(
        ONT, relations={**ONT.relations, "GROUPED_BY": dataclasses.replace(grouped, pairs=pairs)}
    )
    nodes = graph(node("x", FR), node("o", FEAT), module("p"), node("t", CAP))
    edges = [
        link("PART_OF", "x", "o"),
        link("PART_OF", "o", "p"),
        link("GROUPED_BY", "x", "t"),
        link("GROUPED_BY", "o", "t"),
        link("GROUPED_BY", "p", "t"),
    ]
    for ordered in (edges, list(reversed(edges))):
        result = await run(nodes, ordered, ontology=chained)
        assert triples(result) == expect(("x", "PART_OF", "o"), ("o", "PART_OF", "p"), ("p", "GROUPED_BY", "t"))
        assert result.counted["GROUPED_BY"]["redundant"] == 2


