def plan_of(texts: Sequence[str]) -> PlanArtifact:
    fragments = []
    line = 1
    for index, text in enumerate(texts):
        count = len(text.split("\n"))
        fragments.append(
            FragmentRec(
                fragment_id=f"doc#s{index}",
                document_id="doc",
                heading_path=(f"Section {index}",),
                ordinal=index,
                line_start=line,
                line_end=line + count - 1,
                text=text,
                content_hash=f"hash-{index}",
                tokens=max(1, len(text) // 4),
            )
        )
        line += count + 1
    return PlanArtifact(
        mode="first",
        change_set=ChangeSet(new=("doc",)),
        documents=(DocumentRec(document_id="doc", revision_id="doc-r1", version=1, path="doc.md", title="Doc"),),
        fragments=tuple(fragments),
        dirty_ids=tuple(f.fragment_id for f in fragments),
        units=(
            Unit(
                unit_id="doc@u0",
                document_id="doc",
                fragment_ids=tuple(f.fragment_id for f in fragments),
                tokens=10,
                content_hash="unit",
                windows=((0, len(fragments)),),
            ),
        ),
    )


def canonical_node(cid: str, name: str, label: str, key: str) -> CanonicalNode:
    return CanonicalNode(
        cid=cid,
        identity_key=key,
        provisional=False,
        name=name,
        label=label,
        member_ids=(f"raw-{cid}",),
        explicit_ids=(key.rsplit("|", 1)[1],) if "|id|" in key else (),
        fragment_ids=("doc#s0",),
        name_embedding_text=f"{label}: {name}",
    )


async def run_conform(
    gateway: ScriptedGateway,
    nodes: Sequence[CanonicalNode],
    edges: Sequence[tuple[str, str, str, str]],
    attributes: Mapping[str, Mapping[str, str]],
    text: str,
    *,
    store: MemoryStore | None = None,
) -> TargetGraph:
    return await conform(
        plan_of([text]),
        ResolveArtifact(canonical=tuple(sorted(nodes, key=lambda item: item.identity_key))),
        EdgesArtifact(
            raw_edges=tuple(
                RawEdge(relation=rel, source_cid=s, target_cid=t, fact=fact, fragment_ids=("doc#s0",), unit_id="doc@u0")
                for s, rel, t, fact in edges
            ),
            attributes={cid: dict(values) for cid, values in attributes.items()},
        ),
        services=StepServices(gateway=gateway, ontology=ONT, options=BuildOptions()),
        vectors=VectorCache(gateway, MemoryStore(), PROJECT),
        at="2026-01-01T00:00:00+00:00",
        judging=ConformJudging(
            judge_memory=ConformJudgeMemory(store, PROJECT, PROMPT, "judge-model") if store else None
        ),
    )


