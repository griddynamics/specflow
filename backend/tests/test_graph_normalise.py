    assert len(group.loser_ids) == 11
    assert list(group.fragments) == [f"g{index:02}" for index in range(1, 9)]  # one per loser first, at most 8
    few = SpyJudge()
    await normalise(nodes, edges[:4], ONT, judge=few, texts=texts)
    assert list(few.groups[0].fragments) == ["g00", "g01", "g02", "g05"]  # then the winner's


