async def test_other_losers_go_to_one_judge_call_per_group() -> None:
    nodes = graph(node("fr", FR), node("feat", FEAT), module("orders"), module("reporting"), module("web"))
    spy = SpyJudge({"reporting": RELATES_F3, "web": UNRELATED})
    result = await run(
        nodes,
        [
            link("PART_OF", "fr", "feat"),
            link("PART_OF", "feat", "orders"),
            link("PART_OF", "fr", "reporting", fragments=("f3",)),
            link("PART_OF", "fr", "web", fragments=("f2",)),
        ],
        judge=spy,
    )
    (group,) = spy.groups
    assert group.payload["relation"] == "RELATES_TO"
    assert group.payload["subject"]["name"] == "fr" and group.payload["owner"]["name"] == "feat"
    assert [(loser["id"], loser["name"]) for loser in group.payload["losers"]] == [("L1", "reporting"), ("L2", "web")]
    assert list(group.fragments) == ["f1", "f2", "f3"]  # the winner's and each loser's, in document order
    assert triples(result) == expect(
        ("fr", "PART_OF", "feat"), ("feat", "PART_OF", "orders"), ("fr", "RELATES_TO", "reporting")
    )
    assert held(result) == {("judge_rejected", "fr", "PART_OF", "web")}
    kept = next(edge for edge in result.edges if edge.relation == "RELATES_TO")
    assert kept.fact == "generated by the Reporting service"
    assert result.counters.owner_conflicts_judged == 1


