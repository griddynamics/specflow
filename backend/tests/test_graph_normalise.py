def verdict(*answers: Mapping[str, Any], confidence: float = 0.9) -> dict[str, Any]:
    evidence = [item for answer in answers for item in answer.get("evidence", [])]
    return {"confidence": confidence, "evidence": evidence, "answers": list(answers)}


RELATES = {
    "id": "L1",
    "answer": "relates",
    "evidence": [{"fragment_id": "f3", "quote": "generated by the Reporting service"}],
}


def answering(*answers: Any) -> Callable[[ScriptedRequest], Any]:
    queue = list(answers)
    return lambda _: queue.pop(0)


def judge_with(ontology: Ontology = ONT, *, cap: int | None = None, floor: float | None = None) -> Ontology:
    spec = ontology.conform_spec()
    assert spec is not None
    return dataclasses.replace(
        ontology,
        conform=ConformSpec(
            spec.judge_prompt,
            spec.cap if cap is None else cap,
            spec.floor if floor is None else floor,
            spec.fallback_relation,
        ),
    )


