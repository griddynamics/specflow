async def test_every_loser_shows_a_fragment_however_many_there_are() -> None:
    texts = {f"g{index:02}": f"Fragment {index} names module m{index:02}." for index in range(12)}
    losers = [module(f"m{index:02}") for index in range(1, 12)]
