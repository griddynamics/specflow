# Helpers


def node(key: str, label: str, **attributes: str) -> NormNode:
    return NormNode(key, label, key, attributes, (f"{key} statement",))


def module(key: str, kind: str = "backend", external: str = "no") -> NormNode:
    return node(key, MOD, type=kind, external=external, in_scope="yes")


def link(
    relation: str, source: str, target: str, *, basis: Basis = "stated", fragments: Sequence[str] = ("f1",)
) -> NormEdge:
    """An edge as Conform hands it over: a symmetric relation's ends in canonical order."""

    source, relation, target = canonical(relation, source, target)
    return NormEdge(relation, source, target, basis, None, set(fragments))


def graph(*nodes: NormNode) -> dict[str, NormNode]:
    return {item.key: item for item in nodes}


async def run(
    nodes: Mapping[str, NormNode],
    edges: Iterable[NormEdge],
    *,
    judge: Any = None,
    derived: Iterable[NormEdge] = (),
    admit: Callable[[NormEdge], bool] | None = None,
    ontology: Ontology = ONT,
) -> Normalised:
    return await normalise(
        nodes,
        [dataclasses.replace(edge, fragment_ids=set(edge.fragment_ids)) for edge in edges],
        ontology,
        judge=judge or FallbackJudge(),
        texts=TEXTS,
        derived=derived,
        admit=admit,
    )


def canonical(relation: str, source: str, target: str) -> tuple[str, str, str]:
    if relation in SYMMETRIC:
        source, target = min(source, target), max(source, target)
    return source, relation, target


def triples(result: Normalised) -> set[tuple[str, str, str]]:
    return {(edge.source, edge.relation, edge.target) for edge in result.edges}


def expect(*items: tuple[str, str, str]) -> set[tuple[str, str, str]]:
    return {canonical(relation, source, target) for source, relation, target in items}


def held(result: Normalised) -> set[tuple[str, str, str, str]]:
    return {(entry.reason, entry.source, entry.relation, entry.target) for entry in result.quarantine}


def basis_of(result: Normalised, source: str, relation: str, target: str) -> str:
    source, relation, target = canonical(relation, source, target)
    return next(e.basis for e in result.edges if (e.source, e.relation, e.target) == (source, relation, target))


class SpyJudge:
    """Records the groups and answers each loser by its name (``answers``), else the fallback."""

    def __init__(
        self,
        answers: Mapping[str, LoserAnswer] | None = None,
        *,
        outcome: JudgeOutcome = "judged",
        reused: bool = False,
    ) -> None:
        self.answers = dict(answers or {})
        self.outcome = outcome
        self.reused = reused
        self.groups: list[JudgeGroup] = []

    async def decide(self, groups: Sequence[JudgeGroup]) -> list[GroupDecision]:
        self.groups.extend(groups)
        return [
            GroupDecision(
                {loser["id"]: self.answers.get(loser["name"], FALLBACK) for loser in group.payload["losers"]},
                self.outcome,
                reused=self.reused,
            )
            for group in groups
        ]


