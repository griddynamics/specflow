#!/usr/bin/env node
/**
 * Builds the `banned-terms.yml` semgrep rule from a terms file: production code carries no customer,
 * brand, corpus or other project-specific string; an example, a placeholder or a UI string uses a
 * neutral value of the same grammar instead.
 *
 * Usage: node scripts/build-banned-terms.mjs [terms.json] [out.yml]
 *   terms.json  default: banned-terms.example.json next to this kit
 *   out.yml     default: semgrep-ds/banned-terms.yml (the example build the self-test checks);
 *               a project writes <project>/semgrep/banned-terms.yml, which run.mjs loads
 *
 * Terms file shape:
 *   {
 *     "terms": ["Contoso"],              // literal words, matched case-insensitively on word boundaries
 *     "patterns": ["\\bACME-\\d{4}\\b"], // raw regular expressions (Python `re` syntax)
 *     "include": ["**\/src/**"],         // optional: path globs the rule reads (default: every file)
 *     "exclude": ["**\/*.test.ts"]       // path globs the rule skips (test data)
 *   }
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const KIT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const escapeRegExp = (text) => text.replaceAll(/[.*+?^${}()|[\]\\]/gu, '\\$&');

/** The rule's regular expression: one alternation of the escaped terms and the raw patterns. */
export function bannedTermsRegex({ terms = [], patterns = [] }) {
  const arms = [];
  if (terms.length > 0) {
    arms.push(`\\b(?:${terms.map((term) => escapeRegExp(term.toLowerCase())).join('|')})\\b`);
  }
  arms.push(...patterns);
  if (arms.length === 0) throw new Error('banned terms: the terms file lists no term or pattern');
  return `(?i)(?:${arms.join('|')})`;
}

/** The semgrep rule file. JSON strings are valid YAML double-quoted scalars. */
export function renderBannedTerms(config) {
  const exclude = [
    ...(config.exclude ?? ['**/*.test.ts', '**/*.test.tsx', '**/*.test.mjs']),
    '**/banned-terms*.json',
    '**/banned-terms*.yml',
  ];
  return [
    '# Generated by scripts/build-banned-terms.mjs from a terms file; edit the terms file and',
    '# rebuild instead of editing this file.',
    'rules:',
    '  - id: no-project-specific-string',
    '    message: >-',
    '      A customer, brand, corpus or other project-specific string is written into production',
    '      code. Use a neutral value of the same grammar in an example, a placeholder or a UI',
    '      string.',
    '    severity: ERROR',
    '    languages:',
    '      - regex',
    '    paths:',
    ...(config.include === undefined
      ? []
      : ['      include:', ...config.include.map((glob) => `        - ${JSON.stringify(glob)}`)]),
    '      exclude:',
    ...exclude.map((glob) => `        - ${JSON.stringify(glob)}`),
    `    pattern-regex: ${JSON.stringify(bannedTermsRegex(config))}`,
    '',
  ].join('\n');
}

function main(argv) {
  const source = path.resolve(argv[0] ?? path.join(KIT, 'banned-terms.example.json'));
  const target = path.resolve(argv[1] ?? path.join(KIT, 'semgrep-ds', 'banned-terms.yml'));
  const config = JSON.parse(readFileSync(source, 'utf8'));
  writeFileSync(target, renderBannedTerms(config));
  process.stdout.write(`wrote ${target}\n`);
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main(process.argv.slice(2));
}
