"""Renders the two schema-bound Semgrep rules from the declared schema, since a static YAML
rule cannot read a file at match time:

- `kit.sql.delete-outside-allowlist`: `session.delete(obj)` where the variable name does not
  name a hard-delete allow-listed table (`password_reset` or `passwordreset`). Semgrep has no type
  information, so the variable name stands in for the model: `session.delete(row)` holding an
  allow-listed model is a false positive, which a descriptive name avoids.
- `kit.sql.no-mutation-of-append-only-table`: an ORM `update(Model)`/`delete(Model)`
  construct on the model of an append-only table.

A rule whose list is empty is still emitted for the allow-list (every delete is then a
finding) and left out for the append-only tables (nothing to protect)."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import yaml

from sqlcheck.schema import SqlSchema

GENERATED_NAME = "sql_schema.yml"
SESSION_REGEX = "(?i)^_?(db|conn|connection|uow|.*session.*)$"


def _allowlist_tokens(tables: frozenset[str]) -> list[str]:
    tokens = {t.lower() for t in tables} | {t.lower().replace("_", "") for t in tables}
    return sorted((re.escape(t) for t in tokens if t), key=lambda t: (-len(t), t))


def _paths(include: tuple[str, ...]) -> dict[str, Any]:
    return {"include": list(include)}


def render_rules(schema: SqlSchema, paths_include: tuple[str, ...]) -> dict[str, Any]:
    delete_patterns: list[dict[str, Any]] = [
        {"pattern": "$SESSION.delete($OBJ)"},
        {"metavariable-regex": {"metavariable": "$SESSION", "regex": SESSION_REGEX}},
    ]
    tokens = _allowlist_tokens(schema.hard_delete_allowlist)
    if tokens:
        delete_patterns.append(
            {
                "metavariable-regex": {
                    "metavariable": "$OBJ",
                    "regex": f"(?i)^(?!.*({'|'.join(tokens)})).*$",
                }
            }
        )
    allowed = ", ".join(sorted(schema.hard_delete_allowlist)) or "none"
    rules: list[dict[str, Any]] = [
        {
            "id": "kit.sql.delete-outside-allowlist",
            "languages": ["python"],
            "severity": "ERROR",
            "paths": _paths(paths_include),
            "message": (
                "`session.delete(...)` on an object whose name does not name a hard-delete "
                f"allow-listed table ({allowed}). Every other row is deactivated, never "
                "deleted. The rule matches the variable name, not the model it holds."
            ),
            "patterns": delete_patterns,
        }
    ]
    models = sorted({schema.model_name(t) for t in schema.append_only_tables})
    if models:
        alternation = "|".join(re.escape(m) for m in models)
        rules.append(
            {
                "id": "kit.sql.no-mutation-of-append-only-table",
                "languages": ["python"],
                "severity": "ERROR",
                "paths": _paths(paths_include),
                "message": (
                    "An ORM `update()`/`delete()` construct targets the model of an "
                    f"append-only table ({', '.join(models)}). Those rows are only ever "
                    "inserted; they are never edited, deleted or archived."
                ),
                "patterns": [
                    {
                        "pattern-either": [
                            {"pattern": "update($MODEL)"},
                            {"pattern": "delete($MODEL)"},
                            {"pattern": "sqlalchemy.update($MODEL)"},
                            {"pattern": "sqlalchemy.delete($MODEL)"},
                        ]
                    },
                    {
                        "metavariable-regex": {
                            "metavariable": "$MODEL",
                            "regex": f"^({alternation})$",
                        }
                    },
                ],
            }
        )
    return {"rules": rules}


def write_rules(schema: SqlSchema, out_dir: Path, paths_include: tuple[str, ...]) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / GENERATED_NAME
    header = "# Generated by `sqlcheck render-semgrep` from the declared schema. Do not edit.\n"
    body = yaml.safe_dump(render_rules(schema, paths_include), sort_keys=False, width=100)
    target.write_text(header + body, encoding="utf-8")
    return target
